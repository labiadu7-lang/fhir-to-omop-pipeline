SELECT
    ROW_NUMBER() OVER (ORDER BY medication_request_id) AS drug_exposure_id,
    patient_id,
    practitioner_id,
    encounter_id,
    CAST(NULL AS INTEGER) AS person_id,
    CAST(0 AS INTEGER) AS drug_concept_id,
    CAST(authored_datetime AS DATE) AS drug_exposure_start_date,
    authored_datetime AS drug_exposure_start_datetime,
    CAST(authored_datetime AS DATE) AS drug_exposure_end_date,
    authored_datetime AS drug_exposure_end_datetime,
    CAST(NULL AS DATE) AS verbatim_end_date,
    CAST(0 AS INTEGER) AS drug_type_concept_id,
    CAST(NULL AS VARCHAR(20)) AS stop_reason,
    CAST(NULL AS INTEGER) AS refills,
    CAST(NULL AS DOUBLE) AS quantity,
    CAST(NULL AS INTEGER) AS days_supply,
    CAST(NULL AS TEXT) AS sig,
    CAST(0 AS INTEGER) AS route_concept_id,
    CAST(NULL AS VARCHAR(50)) AS lot_number,
    CAST(NULL AS INTEGER) AS provider_id,
    CAST(0 AS INTEGER) AS visit_occurrence_id,
    CAST(NULL AS INTEGER) AS visit_detail_id,
    CAST(medication_code AS VARCHAR(50)) AS drug_source_value,
    CAST(0 AS INTEGER) AS drug_source_concept_id,
    CAST(NULL AS VARCHAR(50)) AS route_source_value,
    CAST(NULL AS VARCHAR(50)) AS dose_unit_source_value
FROM {{ ref('stg_drug_exposure') }}