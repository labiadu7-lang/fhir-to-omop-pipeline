SELECT
    ROW_NUMBER() OVER (ORDER BY observation_id) AS observation_id,
    patient_id,
    encounter_id,
    CAST(NULL AS INTEGER) AS person_id,
    CAST(0 AS INTEGER) AS observation_concept_id,
    CAST(observation_datetime AS DATE) AS observation_date,
    CAST(observation_datetime AS TIMESTAMP) AS observation_datetime,
    CAST(0 AS INTEGER) AS observation_type_concept_id,
    CAST(NULL AS DOUBLE) AS value_as_number,
    CAST(observation_display AS VARCHAR(60)) AS value_as_string,
    CAST(0 AS INTEGER) AS value_as_concept_id,
    CAST(0 AS INTEGER) AS qualifier_concept_id,
    CAST(0 AS INTEGER) AS unit_concept_id,
    CAST(NULL AS INTEGER) AS provider_id,
    CAST(NULL AS INTEGER) AS visit_occurrence_id,
    CAST(NULL AS INTEGER) AS visit_detail_id,
    CAST(observation_code AS VARCHAR(50)) AS observation_source_value,
    CAST(0 AS INTEGER) AS observation_source_concept_id,
    CAST(NULL AS VARCHAR(50)) AS unit_source_value,
    CAST(NULL AS VARCHAR(50)) AS qualifier_source_value,
    CAST(observation_text AS VARCHAR(50)) AS value_source_value,
    CAST(0 AS INTEGER) AS observation_event_id,
    CAST(0 AS INTEGER) AS obs_event_field_concept_id
FROM {{ ref('stg_observation') }}